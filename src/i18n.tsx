const catalogs: Record<Lang, Record<keyof typeof fr, string>> = { fr, en, ar }
export type MessageKey = keyof typeof fr

const LanguageContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void; t: (key: MessageKey, vars?: Record<string, string>) => string } | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const stored = localStorage.getItem('reconcilia-lang')
    return stored === 'en' || stored === 'ar' || stored === 'fr' ? stored : 'fr'
  })
  const setLang = (next: Lang) => {
    localStorage.setItem('reconcilia-lang', next)
    setLangState(next)
  }
  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
  }, [lang])
  const value = useMemo(() => ({
    lang,
    setLang,
    t: (key: MessageKey, vars?: Record<string, string>) => {
      let text = catalogs[lang][key] ?? catalogs.fr[key]
      if (vars) {
        for (const [name, replacement] of Object.entries(vars)) text = text.split(`{${name}}`).join(replacement)
      }
      return text
    },
  }), [lang])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useI18n() {
  const ctx = useContext(LanguageContext)
  if (!ctx) throw new Error('Language absente')
  return ctx
}
